"""Write data/raw/MANIFEST.md: download date (from the macOS quarantine stamp) and SHA256 per raw file.

Reads raw files only; writes MANIFEST.md, the one tracked file in data/raw.
"""
import datetime as dt
import hashlib
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from bnpl.paths import RAW  # noqa: E402


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def xattr(path: Path, name: str) -> str | None:
    r = subprocess.run(["xattr", "-p", name, str(path)], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def download_date(path: Path) -> str:
    q = xattr(path, "com.apple.quarantine")
    if not q:
        return "unknown"
    ts = int(q.split(";")[1], 16)
    return dt.datetime.fromtimestamp(ts, dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def source_url(path: Path) -> str:
    r = subprocess.run(["mdls", "-raw", "-name", "kMDItemWhereFroms", str(path)], capture_output=True, text=True)
    urls = [s.strip().strip('",') for s in r.stdout.splitlines() if "http" in s]
    return urls[0] if urls else "not recorded (CSV extracted from zip)"


def main() -> None:
    files = sorted(p for p in RAW.iterdir() if p.is_file() and p.name not in {"MANIFEST.md", ".DS_Store"})
    lines = [
        "# Raw data manifest",
        "",
        "Generated by `make manifest` (scripts/manifest.py). Raw files are never edited.",
        "",
        "Download date is the macOS quarantine timestamp written by the browser at download.",
        "For the CSVs, that stamp is inherited from the downloaded zip; the file modification",
        "time is the date stored inside the zip by the Fed.",
        "",
        "| File | Bytes | Downloaded | File mtime | Source URL | SHA256 |",
        "|---|---|---|---|---|---|",
    ]
    for p in files:
        mtime = dt.datetime.fromtimestamp(p.stat().st_mtime).strftime("%Y-%m-%d")
        lines.append(
            f"| {p.name} | {p.stat().st_size:,} | {download_date(p)} | {mtime} | {source_url(p)} | `{sha256(p)}` |"
        )
    (RAW / "MANIFEST.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
